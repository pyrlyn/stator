// Writes upper_table.zig: what the pinned Node's `toUpperCase` answers for one UTF-16 unit, which
// `tsFunctionName` applies to the first letter of each `_`-separated part of a C name. Zig's
// standard library has no Unicode case mapping. Run on the pinned Node after bumping it:
//   node packages/tests/zigdiff/gen/gen_upper.ts
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

interface Range {
  from: number;
  to: number;
  stride: number;
  delta: number;
}

const ranges: Range[] = [];
const special: (readonly [number, string])[] = [];

function addRange(unit: number, delta: number): void {
  const last = ranges.at(-1);
  if (last !== undefined && last.delta === delta) {
    const step = unit - last.to;
    if (last.from === last.to ? step <= 2 : step === last.stride) {
      last.stride = step;
      last.to = unit;
      return;
    }
  }
  ranges.push({ from: unit, to: unit, stride: 1, delta });
}

for (let unit = 0x80; unit < 0x10000; unit += 1) {
  // A surrogate alone has no case, and `slice(0, 1)` of an astral letter is exactly that.
  if (unit >= 0xd800 && unit <= 0xdfff) {
    continue;
  }
  const text = String.fromCharCode(unit);
  const upper = text.toUpperCase();
  if (upper === text) {
    continue;
  }
  if (upper.length === 1) {
    addRange(unit, upper.charCodeAt(0) - unit);
  } else {
    special.push([unit, upper]);
  }
}

const rangeRows = ranges.map(
  (r) => `    .{ .from = ${r.from}, .to = ${r.to}, .stride = ${r.stride}, .delta = ${r.delta} },`,
);
const specialRows = special.map(
  ([unit, upper]) =>
    `    .{ .unit = ${unit}, .upper = ${JSON.stringify(upper).replace(/[^\x20-\x7e]/g, (ch) => `\\u{${ch.charCodeAt(0).toString(16)}}`)} },`,
);

const text = `//! Generated by gen_upper.ts on Node ${process.version}. Do not edit.

pub const Range = struct { from: u16, to: u16, stride: u16, delta: i32 };
pub const Special = struct { unit: u16, upper: []const u8 };

pub const ranges = [_]Range{
${rangeRows.join('\n')}
};

pub const special = [_]Special{
${specialRows.join('\n')}
};
`;

const SRC = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..', 'compiler-zig', 'src');
writeFileSync(join(SRC, 'ffigen', 'upper_table.zig'), text);
