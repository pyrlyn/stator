// Writes node_members.zig: what the pinned Node's `builtinModules` and `process.getBuiltinModule`
// answer, which a native compiler has no Node to ask. Run on the pinned Node after bumping it:
//   node packages/tests/zigdiff/gen/gen_node_members.ts
import { writeFileSync } from 'node:fs';
import { builtinModules } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const PREFIX = 'node:';

function isPublic(id: string): boolean {
  return !id.startsWith('_') && !id.startsWith(PREFIX);
}

/** `member in exports` also finds what the prototype chain holds, so the table lists it too. A
 * built-in that exports a function answers no member question at all (`frontend/node.ts`). */
function memberNames(id: string): readonly string[] {
  const exports: unknown = process.getBuiltinModule(`${PREFIX}${id}`);
  if (typeof exports !== 'object' || exports === null) {
    return [];
  }
  const names = new Set<string>();
  for (
    let at: object | null = exports;
    at !== null;
    at = Object.getPrototypeOf(at) as object | null
  ) {
    for (const name of Object.getOwnPropertyNames(at)) {
      names.add(name);
    }
  }
  return [...names].sort();
}

// `zig fmt` writes an empty list as `{}`, so the table needs no formatting pass to stay stable.
const quoted = (list: readonly string[]): string =>
  list.length === 0 ? '' : ` ${list.map((s) => JSON.stringify(s)).join(', ')} `;
const builtin = [
  ...new Set(
    builtinModules.map((m) => m.slice(m.startsWith(PREFIX) ? PREFIX.length : 0)).filter(isPublic),
  ),
].sort();
const bare = builtinModules.filter(isPublic).sort();
const rows = builtin.map(
  (id) => `    .{ .id = ${JSON.stringify(id)}, .names = &.{${quoted(memberNames(id))}} },`,
);

const text = `//! Generated by gen_node_members.ts on Node ${process.version}. Do not edit.
const std = @import("std");

pub const builtin_ids = [_][]const u8{${quoted(builtin)}};
pub const bare_ids = [_][]const u8{${quoted(bare)}};

const Row = struct { id: []const u8, names: []const []const u8 };

/// Sorted: \`hasMember\` searches it.
const rows = [_]Row{
${rows.join('\n')}
};

fn contains(list: []const []const u8, name: []const u8) bool {
    for (list) |item| if (std.mem.eql(u8, item, name)) return true;
    return false;
}

pub fn isBuiltinId(id: []const u8) bool {
    return contains(&builtin_ids, id);
}

pub fn isBareId(id: []const u8) bool {
    return contains(&bare_ids, id);
}

pub fn hasMember(id: []const u8, member: []const u8) bool {
    for (rows) |row| if (std.mem.eql(u8, row.id, id)) return contains(row.names, member);
    return false;
}
`;

const SRC = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..', 'compiler-zig', 'src');
writeFileSync(join(SRC, 'frontend', 'node_members.zig'), text);
